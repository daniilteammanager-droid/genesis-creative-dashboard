--  Авточек: живой чек в привязанный чат по расписанию. Выполнить после
--  019_rejected_ads.sql. Скрипт идемпотентный.
-- ============================================================================
--
--  Расписание — у привязки, а не у человека: в личку можно получать чек по
--  кампаниям в 10:00, а в рабочую группу — по странам в 18:00.
--
--  Время московское и кратно 15 минутам: прогон, который шлёт чек, идёт
--  с VPS ровно раз в четверть часа (:00, :15, :30, :45).

alter table public.telegram_links
  add column if not exists check_times   text[] not null default '{}',     -- {"10:00","18:30"}
  add column if not exists check_group   text   not null default 'campaign'
    check (check_group in ('campaign', 'creative', 'country')),
  -- Какой слот уже отправлен: «2026-10-24 10:00». Повторный прогон в ту же
  -- четверть часа второй чек не шлёт.
  add column if not exists check_sent_slot text;
