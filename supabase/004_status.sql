-- Проблема: колонка profiles.status была чисто приложенческой отметкой.
-- Ни одна политика RLS её не смотрела, а app_is_main() спрашивала только роль.
-- Из-за этого отключённый владелец мог позвать admin_update_profile и включить
-- себя обратно: функция проверяет app_is_main(), а та про status не знала.
--
-- Достаточно починить в одном месте — app_role(). Через неё смотрят и
-- app_is_main(), и политики на profiles и teamlead_buyers.
create or replace function public.app_role()
returns public.user_role
language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() and status = 'active' $$;

-- Свой профиль отключённый по-прежнему читает (политика profiles_select пускает
-- по id = auth.uid()) — иначе интерфейс не смог бы объяснить, что происходит.
-- А вот чужие строки, приглашения и смена ролей для него закрыты.

