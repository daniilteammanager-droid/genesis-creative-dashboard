-- ============================================================================
--  Кто владеет рекламным кабинетом. Выполнить после 012_adset_geo.sql.
--  Скрипт идемпотентный.
-- ============================================================================
--
--  ЗАЧЕМ. Мы закладывались, что разграничение получится само: баер подключает
--  свой ключ Meta, значит и отчёт собирается по его данным (Decision 035). На
--  живых данных это оказалось неверно — замер 03.09.2026: у Артёма и Матвея в
--  складе одни и те же 82 строки, те же 4 кабинета и почти тот же спенд, потому
--  что оба токена сняты с аккаунта владельца и видят все 78 кабинетов команды.
--
--  Meta развести их не может: доступ несёт пользователь, от чьего имени выпущен
--  токен, а выбор кабинетов при авторизации привязан к самому токену и требует
--  перевыдачи при каждой смене БМ. Команда меняет БМ по нескольку раз в день,
--  поэтому такой ценой разграничение не покупается.
--
--  РЕШЕНИЕ. Владение кабинетом объявляется здесь, в дашборде, владельцем.
--  Один кабинет — один баер. Это не догадка по данным: строка появляется
--  только когда человек её поставил.
--
--  Кабинет без владельца — это не ошибка, а состояние «ещё не распределён».
--  Баерам такой кабинет не показывается вообще, владелец видит его отдельно и
--  с суммой расхода: деньги не должны теряться молча.
create table if not exists public.wh_account_owners (
  -- id рекламного кабинета Meta, без префикса act_ — так он лежит в wh_ad_days.
  account_id     text primary key,
  -- Кому принадлежит. null — не распределён.
  -- restrict: отключение баера не должно тихо обнулять владение кабинетом,
  -- иначе его расход исчезнет из отчётов вместе с человеком (Decision 033).
  owner_user_id  uuid references public.profiles(id) on delete restrict,
  assigned_by    uuid references public.profiles(id) on delete set null,
  assigned_at    timestamptz not null default now()
);

create index if not exists wh_account_owners_by_owner
  on public.wh_account_owners (owner_user_id);

-- Чтение склада теперь фильтруется по кабинету, а не по тому, чей токен принёс
-- строку. Без этого индекса такой фильтр шёл бы перебором всей таблицы.
create index if not exists wh_ad_days_by_account
  on public.wh_ad_days (account_id, date);
create index if not exists wh_campaign_days_by_account
  on public.wh_campaign_days (account_id, date);

alter table public.wh_account_owners enable row level security;
revoke all on public.wh_account_owners from anon, authenticated;
