-- ============================================================================
--  Страна как факт, а не как строка из названия. После 011. Идемпотентный.
-- ============================================================================
--
--  Гео нельзя брать из нейминга: старые имена продолжают работать, шаблон
--  адсета соблюдён не у всех, и пишет его человек — значит однажды ошибётся.
--  Замер 31.08.2026 это подтвердил: рядом уживаются "T2A/72 25.08 BROAD SPAIN
--  LANG" и "29.08 - ARG-ES - EDIT-18 - 154726", ни одно не по шаблону.
--
--  Факт лежит в настройках таргета адсета. Замер: 109 адсетов, у 108 ровно одна
--  страна, у одного полторы сотни (он и называется WORLD), без страны — ноль.
--  Стоит одна выборка на кабинет, не на адсет.
--
--  Таблица без user_id намеренно: таргет — свойство самого адсета, а не чей-то
--  взгляд на него. Кому что видно, решает связь с wh_ad_days, где user_id есть.
create table if not exists public.wh_adsets (
  adset_id    text primary key,
  adset_name  text,
  account_id  text,
  -- Список стран таргета. Одна страна — доход адсета принадлежит ей целиком.
  -- Несколько — разделить доход нечем, и такие показываются отдельно, а не
  -- размазываются: правдоподобная цифра хуже честного прочерка.
  countries   text[] not null default '{}',
  updated_at  timestamptz not null default now()
);

create index if not exists wh_adsets_by_country on public.wh_adsets using gin (countries);

alter table public.wh_adsets enable row level security;
revoke all on public.wh_adsets from anon, authenticated;
