// подход ("storytell") вместо гео — то есть все новые креативы уезжали в "Без гео".
// Код не распознан → бакет "Без гео", не догадываемся.
//
// Список значений временно живёт здесь. Его место — справочник ГЕО в словаре команды,
// переезд в Фазе 3, тогда новая страна перестанет требовать деплой.
