import type { AccountScope } from "./metaApi";

// Источник живого чека: один ключ Meta (Decision 061).
//
// Раньше здесь же жила командная конфигурация из переменных окружения — ключ
// владельца и выгрузки Torro в таблицы. Её больше нет: сводная — это сумма
// интеграций всех, а Torro берётся только по API.

export interface ReportConfig {
  // Ключ кэша. Общий кэш без него означал бы, что один баер получает
  // закэшированные цифры другого — молча и правдоподобно.
  cacheKey: string;
  metaToken: string;
  // Какие кабинеты считать своими. У баера — только назначенные его токену,
  // иначе системный пользователь с тремя кабинетами превращается обратно во
  // «все кабинеты бизнеса» (Decision 050).
  accountScope: AccountScope;
  // Остались от выгрузок; пустые строки, пока тип не уберём целиком.
  campaignsSheetId: string;
  adsSheetId: string;
}
